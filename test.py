# 1. ТЕСТ КЛАССОВ И МЕТОДОВ (ООП)
class Робот:
    #аналог __init__
    def __init__(self, имя, модель):
        self.имя = имя
        self.модель = модель
        self.энергия = 100
        self.инвентарь = []

    def статус(self):
        print("--- ОТЧЕТ СИСТЕМЫ ---")
        print("Имя: " + self.имя)
        print("Заряд: " + str(self.энергия) + "%")
        print("Предметы: " + str(self.инвентарь))

    def взять_вещь(self, предмет):
        self.инвентарь.append(предмет)
        print(self.имя + " положил в сумку: " + предмет)

    def работа(self, задача):
        if self.энергия > 20:
            print("Выполняю: " + задача)
            self.энергия = self.энергия - 30
        else:
            print("НИЗКИЙ ЗАРЯД! Работа невозможна.")

